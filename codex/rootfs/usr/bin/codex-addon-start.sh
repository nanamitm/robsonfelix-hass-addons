#!/usr/bin/env bash
# Home Assistant add-on entrypoint.
#
# Renders the add-on options into /etc/codex/config.toml - the lowest-precedence
# config layer Codex loads - and then hands the terminal to ttyd. Writing the
# system layer instead of $CODEX_HOME/config.toml keeps the user's own config
# file untouched and always winning, and keeps generated settings out of the
# Home Assistant config directory, which is part of every backup.
set -euo pipefail

OPTIONS=/data/options.json
SYSTEM_CONFIG_DIR=/etc/codex
SYSTEM_CONFIG="$SYSTEM_CONFIG_DIR/config.toml"

export CODEX_HOME="${CODEX_HOME:-/homeassistant/.codex}"

# hass-mcp reads these from the environment. They are deliberately not written
# to any file: $SUPERVISOR_TOKEN is a live credential, and $CODEX_HOME lives in
# the HA config directory, which ships inside every backup.
export HA_TOKEN="${SUPERVISOR_TOKEN:-}"
export HA_URL="http://supervisor/core"

opt() { jq -r "$1" "$OPTIONS"; }

# Options typed as `str` in config.yaml can contain anything, including the two
# characters that would end a TOML basic string early and corrupt the whole
# generated file.
toml_escape() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }

ENABLE_MCP=$(opt 'if .enable_mcp == null then true else .enable_mcp end')
ENABLE_PLAYWRIGHT=$(opt '.enable_playwright_mcp // false')
PLAYWRIGHT_HOST=$(opt '.playwright_cdp_host // ""')
MODEL=$(opt '.model // ""')
APPROVAL=$(opt '.approval_policy // "on-request"')
SANDBOX=$(opt '.sandbox_mode // "danger-full-access"')
EFFORT=$(opt '.model_reasoning_effort // "default"')
FONT_SIZE=$(opt '.terminal_font_size // 14')
THEME=$(opt '.terminal_theme // "dark"')
WORKDIR=$(opt '.working_directory // "/homeassistant"')
SESSION_PERSIST=$(opt 'if .session_persistence == null then true else .session_persistence end')
AUTO_UPDATE=$(opt '.auto_update_codex // false')
USAGE_SENSORS=$(opt 'if .usage_sensors == null then true else .usage_sensors end')
USAGE_POLL=$(opt '.usage_poll_seconds // 60')

# A working_directory that does not exist would otherwise take the entrypoint
# down before ttyd starts, leaving no terminal to correct the option from.
if [ ! -d "$WORKDIR" ]; then
    echo "[WARN] working_directory $WORKDIR does not exist; falling back to /homeassistant"
    WORKDIR=/homeassistant
fi

mkdir -p "$CODEX_HOME" "$SYSTEM_CONFIG_DIR"

if [ "$AUTO_UPDATE" = "true" ]; then
    # install-codex.sh only replaces the CLI once the new one has proved it
    # runs, so this really does leave a working install behind.
    /usr/local/bin/install-codex.sh "$(uname -m)" || echo '[WARN] Update failed; the previous version is untouched'
fi
CODEX_VERSION=$(timeout 30 codex --version 2>/dev/null || echo '(not responding)')
echo "[INFO] Codex $CODEX_VERSION"

# Global instructions, refreshed so that add-on updates ship new guidance - but
# only while the file is still the copy this add-on wrote. $CODEX_HOME/AGENTS.md
# is also where Codex's own docs tell users to put global instructions, and
# overwriting those would destroy work the user cannot get back.
#
# Ownership is decided by content hash: the marker records what was last
# installed, and AGENTS.md.superseded lists what earlier add-on versions
# shipped. Without that list, upgrading from a version that predates the marker
# reports every untouched file as edited and freezes it for good.
SHIPPED_AGENTS=/usr/share/codex-addon/AGENTS.md
AGENTS_MARKER="$CODEX_HOME/.agents-md-installed.sha256"
agents_is_ours() {
    [ -f "$CODEX_HOME/AGENTS.md" ] || return 1
    local current
    current=$(sha256sum < "$CODEX_HOME/AGENTS.md" | cut -d' ' -f1)
    [ "$current" != "$(cat "$AGENTS_MARKER" 2>/dev/null || true)" ] || return 0
    grep -q "^$current[[:space:]]" "$SHIPPED_AGENTS.superseded" 2>/dev/null
}
if [ ! -f "$CODEX_HOME/AGENTS.md" ] || agents_is_ours; then
    install -m 0644 "$SHIPPED_AGENTS" "$CODEX_HOME/AGENTS.md"
    sha256sum < "$SHIPPED_AGENTS" | cut -d' ' -f1 > "$AGENTS_MARKER"
else
    echo "[INFO] $CODEX_HOME/AGENTS.md has been edited; leaving it as it is"
    echo '[INFO] Delete it to get the add-on version back, or keep your own notes in AGENTS.override.md'
fi

if [ -z "$PLAYWRIGHT_HOST" ] && [ "$ENABLE_PLAYWRIGHT" = "true" ]; then
    echo '[INFO] Auto-detecting Playwright Browser hostname...'
    PLAYWRIGHT_HOST=$(curl -s -H "Authorization: Bearer $SUPERVISOR_TOKEN" http://supervisor/addons \
        | jq -r '.data.addons[] | select(.slug | endswith("playwright-browser") or endswith("_playwright-browser")) | .hostname' \
        | head -1) || true
    if [ -n "$PLAYWRIGHT_HOST" ] && [ "$PLAYWRIGHT_HOST" != "null" ]; then
        echo "[INFO] Found Playwright Browser: $PLAYWRIGHT_HOST"
    else
        echo '[WARN] Playwright Browser add-on not found, using default hostname'
        PLAYWRIGHT_HOST=playwright-browser
    fi
fi

{
    echo '# Generated by the Codex add-on on every start - edits here are lost.'
    echo '# This is the lowest-precedence layer: anything you put in'
    echo "# $CODEX_HOME/config.toml overrides it."
    echo
    if [ -n "$MODEL" ] && [ "$MODEL" != "null" ]; then
        printf 'model = "%s"\n' "$(toml_escape "$MODEL")"
    fi
    printf 'approval_policy = "%s"\n' "$APPROVAL"
    printf 'sandbox_mode = "%s"\n' "$SANDBOX"
    if [ "$EFFORT" != "default" ]; then
        printf 'model_reasoning_effort = "%s"\n' "$EFFORT"
    fi
    echo
    # Skip the "do you trust this folder?" prompt: the add-on already runs as
    # root with the HA config directory mounted read-write.
    printf '[projects."%s"]\ntrust_level = "trusted"\n' "$(toml_escape "$WORKDIR")"
    if [ "$ENABLE_MCP" = "true" ]; then
        # Codex hands an MCP server a fixed allowlist of variables - HOME, PATH,
        # SHELL, USER, LANG and a few more - and nothing else, so hass-mcp never
        # saw the credentials this script exports. env_vars names the extra ones
        # to forward from the running process, which keeps the Supervisor token
        # out of every file on disk; the alternative, an `env` table, would write
        # the live token into this config.
        printf '\n[mcp_servers.homeassistant]\ncommand = "hass-mcp"\nenv_vars = ["HA_URL", "HA_TOKEN"]\n'
    fi
    if [ "$ENABLE_PLAYWRIGHT" = "true" ]; then
        printf '\n[mcp_servers.playwright]\ncommand = "npx"\n'
        printf 'args = ["--no-install", "@playwright/mcp", "--cdp-endpoint", "http://%s:9222"]\n' "$(toml_escape "$PLAYWRIGHT_HOST")"
    fi
} > "$SYSTEM_CONFIG"

if [ "$ENABLE_MCP" = "true" ]; then
    # Confirm Codex really merges the system layer, so a release that stopped
    # doing so shows up here instead of as a Codex that quietly cannot see Home
    # Assistant. There is no safe automatic fallback: `codex mcp add` writes to
    # the user config and cannot set env_vars, so the only way to give hass-mcp
    # its token from there would be to persist the token itself.
    if timeout 30 codex mcp list 2>/dev/null | grep -q '^homeassistant[[:space:]]'; then
        echo '[INFO] Home Assistant MCP server configured'
    else
        echo '[ERROR] Codex did not pick up /etc/codex/config.toml, so the Home Assistant'
        echo '[ERROR] MCP server is not registered. Report this - it means the config layer'
        echo '[ERROR] this add-on relies on has changed.'
    fi
else
    echo '[INFO] Home Assistant MCP disabled'
fi

if [ "$SANDBOX" != "danger-full-access" ]; then
    if ! timeout 20 codex sandbox -- true > /dev/null 2>&1; then
        echo "[WARN] sandbox_mode=$SANDBOX cannot run here: bubblewrap needs a user namespace, which this"
        echo '[WARN] container is not allowed to create. Codex will fail as soon as it runs a command.'
        echo '[WARN] Set sandbox_mode to danger-full-access - the add-on container is the boundary then,'
        echo '[WARN] the same one every other add-on runs behind - and keep approval_policy at on-request.'
    fi
fi

if [ ! -f "$CODEX_HOME/auth.json" ]; then
    echo '[INFO] Not signed in yet. In the terminal, run: codex login --device-auth'
fi

# Publishes Codex's own rate-limit usage to Home Assistant as MQTT sensors.
# It runs beside the terminal rather than as its own add-on because that is the
# only place the Codex sign-in exists: it reads $CODEX_HOME/auth.json, and never
# writes to it - the CLI in the terminal owns that file, and a refresh from
# behind its back rotates the refresh token out from under it.
start_usage_bridge() {
    local service host port ssl username password

    # `mqtt:want` means the Supervisor hands over the broker details when one is
    # configured and declines when there is none, so a failure here is a missing
    # broker rather than a broken add-on.
    service=$(curl -sf -H "Authorization: Bearer $SUPERVISOR_TOKEN" \
        http://supervisor/services/mqtt 2>/dev/null) || service=''
    if [ -z "$service" ]; then
        echo '[WARN] usage_sensors is on, but this add-on has no MQTT broker.'
        echo '[WARN] Install and start the Mosquitto broker add-on, then restart this one.'
        return
    fi

    host=$(echo "$service" | jq -r '.data.host // empty')
    port=$(echo "$service" | jq -r '.data.port // 1883')
    ssl=$(echo "$service" | jq -r '.data.ssl // false')
    username=$(echo "$service" | jq -r '.data.username // empty')
    password=$(echo "$service" | jq -r '.data.password // empty')

    if [ -z "$host" ]; then
        echo '[WARN] The MQTT service gave no hostname; usage sensors are off'
        return
    fi

    # A subshell so the broker password stays out of the environment ttyd hands
    # to the user's shell, and out of `ps`, which naming them on a command line
    # would not.
    (
        # The bridge talks to OpenAI and to the broker, and to nothing else in
        # Home Assistant, so it has no use for the Supervisor credentials this
        # script exports for hass-mcp.
        unset SUPERVISOR_TOKEN HA_TOKEN HA_URL

        export MQTT_HOST="$host" MQTT_PORT="$port" MQTT_SSL="$ssl" \
            MQTT_USERNAME="$username" MQTT_PASSWORD="$password" \
            CODEX_HOME="$CODEX_HOME" CODEX_VERSION="$CODEX_VERSION" \
            USAGE_POLL_SECONDS="$USAGE_POLL"

        # The bridge exits instead of reconnecting, so restarting it here is the
        # whole recovery story - for a broker that reboots as much as for one
        # that was not up yet when the add-on started.
        while true; do
            node /usr/share/codex-addon/usage-bridge/index.js || true
            sleep 30
        done
    ) &

    echo "[INFO] Usage sensors publishing to $host:$port every ${USAGE_POLL}s"
}

if [ "$USAGE_SENSORS" = "true" ]; then
    start_usage_bridge
else
    echo '[INFO] Usage sensors disabled'
fi

if [ "$THEME" = "dark" ]; then
    COLORS='background=#1e1e2e,foreground=#cdd6f4,cursor=#f5e0dc'
else
    COLORS='background=#eff1f5,foreground=#4c4f69,cursor=#dc8a78'
fi

if [ "$SESSION_PERSIST" = "true" ]; then
    SHELL_CMD=(tmux new-session -A -s codex)
else
    SHELL_CMD=(bash --login)
fi

cd "$WORKDIR" || cd /homeassistant
exec ttyd --port 7681 --writable --ping-interval 30 --max-clients 5 \
    -t "fontSize=$FONT_SIZE" \
    -t fontFamily=Monaco,Consolas,monospace \
    -t scrollback=20000 \
    -t "theme=$COLORS" \
    "${SHELL_CMD[@]}"
