#!/usr/bin/env bash
# Home Assistant add-on entrypoint.
#
# Renders the add-on options into /etc/codex/config.toml - the lowest-precedence
# config layer Codex loads - and then hands the terminal to ttyd. Writing the
# system layer instead of $CODEX_HOME/config.toml keeps the user's own config
# file untouched and always winning, and keeps generated settings out of the
# Home Assistant config directory, which is part of every backup.
set -euo pipefail

OPTIONS=/data/options.json
SYSTEM_CONFIG_DIR=/etc/codex
SYSTEM_CONFIG="$SYSTEM_CONFIG_DIR/config.toml"

export CODEX_HOME="${CODEX_HOME:-/homeassistant/.codex}"

# hass-mcp reads these from the environment. They are deliberately not written
# to any file: $SUPERVISOR_TOKEN is a live credential, and $CODEX_HOME lives in
# the HA config directory, which ships inside every backup.
export HA_TOKEN="${SUPERVISOR_TOKEN:-}"
export HA_URL="http://supervisor/core"

opt() { jq -r "$1" "$OPTIONS"; }

ENABLE_MCP=$(opt 'if .enable_mcp == null then true else .enable_mcp end')
ENABLE_PLAYWRIGHT=$(opt '.enable_playwright_mcp // false')
PLAYWRIGHT_HOST=$(opt '.playwright_cdp_host // ""')
MODEL=$(opt '.model // ""')
APPROVAL=$(opt '.approval_policy // "on-request"')
SANDBOX=$(opt '.sandbox_mode // "danger-full-access"')
EFFORT=$(opt '.model_reasoning_effort // "default"')
FONT_SIZE=$(opt '.terminal_font_size // 14')
THEME=$(opt '.terminal_theme // "dark"')
WORKDIR=$(opt '.working_directory // "/homeassistant"')
SESSION_PERSIST=$(opt 'if .session_persistence == null then true else .session_persistence end')
AUTO_UPDATE=$(opt '.auto_update_codex // false')

mkdir -p "$CODEX_HOME" "$SYSTEM_CONFIG_DIR"

if [ "$AUTO_UPDATE" = "true" ]; then
    /usr/local/bin/install-codex.sh "$(uname -m)" || echo '[WARN] Update failed; keeping the installed version'
fi
echo "[INFO] Codex $(codex --version 2>/dev/null || echo '(not responding)')"

# Global instructions. Rewritten on every start so add-on updates ship new
# guidance; Codex prefers AGENTS.override.md, so that is where user edits go.
install -m 0644 /usr/share/codex-addon/AGENTS.md "$CODEX_HOME/AGENTS.md"

if [ -z "$PLAYWRIGHT_HOST" ] && [ "$ENABLE_PLAYWRIGHT" = "true" ]; then
    echo '[INFO] Auto-detecting Playwright Browser hostname...'
    PLAYWRIGHT_HOST=$(curl -s -H "Authorization: Bearer $SUPERVISOR_TOKEN" http://supervisor/addons \
        | jq -r '.data.addons[] | select(.slug | endswith("playwright-browser") or endswith("_playwright-browser")) | .hostname' \
        | head -1) || true
    if [ -n "$PLAYWRIGHT_HOST" ] && [ "$PLAYWRIGHT_HOST" != "null" ]; then
        echo "[INFO] Found Playwright Browser: $PLAYWRIGHT_HOST"
    else
        echo '[WARN] Playwright Browser add-on not found, using default hostname'
        PLAYWRIGHT_HOST=playwright-browser
    fi
fi

{
    echo '# Generated by the Codex add-on on every start - edits here are lost.'
    echo '# This is the lowest-precedence layer: anything you put in'
    echo "# $CODEX_HOME/config.toml overrides it."
    echo
    if [ -n "$MODEL" ] && [ "$MODEL" != "null" ]; then
        printf 'model = "%s"\n' "$MODEL"
    fi
    printf 'approval_policy = "%s"\n' "$APPROVAL"
    printf 'sandbox_mode = "%s"\n' "$SANDBOX"
    if [ "$EFFORT" != "default" ]; then
        printf 'model_reasoning_effort = "%s"\n' "$EFFORT"
    fi
    echo
    # Skip the "do you trust this folder?" prompt: the add-on already runs as
    # root with the HA config directory mounted read-write.
    printf '[projects."%s"]\ntrust_level = "trusted"\n' "$WORKDIR"
    if [ "$ENABLE_MCP" = "true" ]; then
        # Codex hands an MCP server a fixed allowlist of variables - HOME, PATH,
        # SHELL, USER, LANG and a few more - and nothing else, so hass-mcp never
        # saw the credentials this script exports. env_vars names the extra ones
        # to forward from the running process, which keeps the Supervisor token
        # out of every file on disk; the alternative, an `env` table, would write
        # the live token into this config.
        printf '\n[mcp_servers.homeassistant]\ncommand = "hass-mcp"\nenv_vars = ["HA_URL", "HA_TOKEN"]\n'
    fi
    if [ "$ENABLE_PLAYWRIGHT" = "true" ]; then
        printf '\n[mcp_servers.playwright]\ncommand = "npx"\n'
        printf 'args = ["--no-install", "@playwright/mcp", "--cdp-endpoint", "http://%s:9222"]\n' "$PLAYWRIGHT_HOST"
    fi
} > "$SYSTEM_CONFIG"

if [ "$ENABLE_MCP" = "true" ]; then
    # Confirm Codex really merges the system layer, so a release that stopped
    # doing so shows up here instead of as a Codex that quietly cannot see Home
    # Assistant. There is no safe automatic fallback: `codex mcp add` writes to
    # the user config and cannot set env_vars, so the only way to give hass-mcp
    # its token from there would be to persist the token itself.
    if codex mcp list 2>/dev/null | grep -q '^homeassistant[[:space:]]'; then
        echo '[INFO] Home Assistant MCP server configured'
    else
        echo '[ERROR] Codex did not pick up /etc/codex/config.toml, so the Home Assistant'
        echo '[ERROR] MCP server is not registered. Report this - it means the config layer'
        echo '[ERROR] this add-on relies on has changed.'
    fi
else
    echo '[INFO] Home Assistant MCP disabled'
fi

if [ "$SANDBOX" != "danger-full-access" ]; then
    if ! timeout 20 codex sandbox -- true > /dev/null 2>&1; then
        echo "[WARN] sandbox_mode=$SANDBOX cannot run here: bubblewrap needs a user namespace, which this"
        echo '[WARN] container is not allowed to create. Codex will fail as soon as it runs a command.'
        echo '[WARN] Set sandbox_mode to danger-full-access - the add-on container is the boundary then,'
        echo '[WARN] the same one every other add-on runs behind - and keep approval_policy at on-request.'
    fi
fi

if [ ! -f "$CODEX_HOME/auth.json" ]; then
    echo '[INFO] Not signed in yet. In the terminal, run: codex login --device-auth'
fi

if [ "$THEME" = "dark" ]; then
    COLORS='background=#1e1e2e,foreground=#cdd6f4,cursor=#f5e0dc'
else
    COLORS='background=#eff1f5,foreground=#4c4f69,cursor=#dc8a78'
fi

if [ "$SESSION_PERSIST" = "true" ]; then
    SHELL_CMD=(tmux new-session -A -s codex)
else
    SHELL_CMD=(bash --login)
fi

cd "$WORKDIR"
exec ttyd --port 7681 --writable --ping-interval 30 --max-clients 5 \
    -t "fontSize=$FONT_SIZE" \
    -t fontFamily=Monaco,Consolas,monospace \
    -t scrollback=20000 \
    -t "theme=$COLORS" \
    "${SHELL_CMD[@]}"
